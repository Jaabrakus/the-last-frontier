#!/usr/bin/env python3
"""Resolve the graph selections the loadout needs for Actor_B: the NO-WEAPON profile (hands free /
sling all / climbing) and the BACKPACK-OFF draw / holster clips (a character without a backpack).

    python3 tools/loadout/resolve_loadout_graph.py [--pap <Player_Animation_Project>] [--out data/loadout/graph_selections.json]

Frontier's graph export (tools/anim_graph/export_actor_b_graph.py) resolves three weapon profiles
(bow, musket, pistol). The extracted graph also has the selections the game uses when nothing is in
the hands: `anim-overlay-player-weapon-base-no-weapon` and
`anim-overlay-player-weapon-draw-holster-no-weapon` (both have 0 remap records), plus
`anim-overlay-player-weapon-melee-base-no-weapon` (17 records, melee only). This script reuses the
exporter's resolver (imported, never modified; same overlay loop, bindings.resolver_policy) with an
in-memory "unarmed" profile and writes, per mode, the lower-body roles the loadout's hands-free
state needs, the hand states (idle-hands / weapon-out fingers), the draw / holster action leaves and
a diff against the pistol profile (the profile Frontier treats as the graph default).

Backpack-off: the graph's `anim-overlay-player-backpack-off` set (layer `backpack`, 6 records) swaps the
pistol draw / grab / stow clips for their `--no-pack` variants. The frontier character wears no
backpack, so this is the graph-faithful selection for it. Every weapon x stance x draw / holster
action is resolved with and without it (actions.<w>/<stance>/<key>: partial and twin leaves).

Only reads: the exporter's inputs (PAP player_blending.json, blender_animation_index.csv,
graph_analysis/graph/*.json, tools/anim_graph/frontier_bindings.json, actor_b_keyed_bones.json).
Writes only --out. Python 3.9, standard library.

Provenance: record offsets and 32-bit IDs are copied from the graph, never re-hashed.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys

sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
FR_ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(FR_ROOT, "tools", "anim_graph"))

import export_actor_b_graph as X  # noqa: E402

GENERATOR = "tools/loadout/resolve_loadout_graph.py"
BACKPACK_OFF = "anim-overlay-player-backpack-off"
UNARMED = {
    "weapon-base": "anim-overlay-player-weapon-base-no-weapon",
    "weapon-sub-type": None,
    "weapon-draw-holster": "anim-overlay-player-weapon-draw-holster-no-weapon",
}
## Lower-body roles worth listing for the hands-free state (the rest are resolved too).
KEY_ROLES = ["idle", "fw", "bw", "start_fw", "stop_fw", "turn_l", "turn_r", "jump", "fall", "land_soft_idle",
             "land_soft_run", "hit_add", "death"]


def slim(role):
    return {
        "clip": role.get("clip"), "graph_clip": role.get("graph_clip"), "status": role.get("status"),
        "state": role.get("state"), "state_offset": role.get("state_offset"), "leaf": role.get("leaf"),
        "leaf_id": role.get("leaf_id"), "final_id": role.get("final_id"),
        "chain": [[c["layer"], c["set"], c["record_offset"], c["from"], c["to"]] for c in role.get("chain", [])],
        "layers": [{"clip": l.get("clip") or ("MISSING " + str(l.get("graph_clip"))), "weight": l.get("weight"),
                    "slot": l.get("slot"), "kind": l.get("kind"), "set": l.get("set"),
                    "record_offset": l.get("record_offset"), "weight_expr": l.get("weight_expr")}
                   for l in role.get("layers", [])],
        "resolution": role.get("resolution", "unique"),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pap", default=os.environ.get("ANIM_GRAPH_PAP", X.DEFAULT_PAP))
    ap.add_argument("--out", default=os.path.join(FR_ROOT, "data", "loadout", "graph_selections.json"))
    a = ap.parse_args(argv)
    ex = X.Exporter(a.pap)
    ex._gstate_cache = {}
    B = ex.B
    B["profiles"] = copy.deepcopy(B["profiles"])
    B["profiles"]["unarmed"] = dict(UNARMED)
    for sn in UNARMED.values():
        if sn and sn not in ex.db.sets:
            raise SystemExit(f"overlay set {sn} missing from the graph")
    set_sizes = {sn: len(ex.db.sets[sn]["remaps"]) for sn in UNARMED.values() if sn}
    melee_nw = "anim-overlay-player-weapon-melee-base-no-weapon"
    set_sizes[melee_nw] = len(ex.db.sets[melee_nw]["remaps"]) if melee_nw in ex.db.sets else None

    out = {"about": ("Actor_B graph selections for the loadout, resolved from the extracted graph with the exporter's "
                     "resolver: the no-weapon profile (weapon-base-no-weapon, weapon-draw-holster-no-weapon) for the "
                     "hands-free / sling-all / climbing state, and the backpack-off draw / holster clips. Generated by "
                     "%s; do not edit." % GENERATOR),
           "generator": GENERATOR, "authorization": X.AUTHORIZATION,
           "resolver": ex.resolver, "profile": UNARMED, "set_remap_counts": set_sizes,
           "selections": {}, "roles": {}, "key_roles": {}, "hand_states": {}, "actions": {},
           "diff_vs_pistol": {}, "diff_vs_musket": {}, "melee_base_no_weapon": []}
    modes = list(B["modes"])
    for m in modes:
        sel = ex.selection("unarmed", m)
        out["selections"][m] = {layer: sn for layer, sn in ex.ordered(sel)}
        for rk, spec in B["lower_roles"].items():
            role = ex.build_role(spec["state"], spec["leaf"], sel, f"unarmed.roles.{m}/{rk}")
            out["roles"][f"{m}/{rk}"] = slim(role)
            for other, dk in (("pistol", "diff_vs_pistol"), ("musket", "diff_vs_musket")):
                r2 = ex.build_role(spec["state"], spec["leaf"], ex.selection(other, m), f"cmp.{other}.{m}/{rk}")
                a1 = (role.get("clip"), tuple((l.get("clip"), l.get("weight")) for l in role.get("layers", [])))
                a2 = (r2.get("clip"), tuple((l.get("clip"), l.get("weight")) for l in r2.get("layers", [])))
                if a1 != a2:
                    out[dk][f"{m}/{rk}"] = {"unarmed": [a1[0], [list(x) for x in a1[1]]],
                                            other: [a2[0], [list(x) for x in a2[1]]]}
        for rk in KEY_ROLES:
            r = out["roles"].get(f"{m}/{rk}")
            if r:
                out["key_roles"][f"{m}/{rk}"] = [r["clip"]] + [f"{l['clip']} x{l['weight']} ({l['slot']})"
                                                              for l in r["layers"]]
    for st in ("stand", "crouch"):
        mk = B["stance_selection_mode"][st]
        sel = ex.selection("unarmed", mk)
        hs = {}
        for rk, spec in B["hand_states"].items():
            hs[rk] = slim(ex.build_role(spec["state"], spec["leaf"], sel, f"unarmed.hand_states.{st}.{rk}"))
        out["hand_states"][st] = hs
        for key, spec in B["actions"].items():
            if key not in ("grab", "equip", "holster", "holster_finish"):
                continue
            s = ex.state(spec["state"])
            leaves = ex.tree_leaves(s["tree"])
            ent = {"state": spec["state"], "state_offset": s["offset"], "leaves": []}
            for lf in leaves:
                r = ex.build_role_from_id(spec["state"], lf["clip"], lf["clip_id"], sel,
                                          f"unarmed.actions.{st}.{key}", lf)
                ent["leaves"].append(slim(r))
            out["actions"][f"{st}/{key}"] = ent
    if melee_nw in ex.db.sets:
        for r in ex.db.sets[melee_nw]["remaps"]:
            out["melee_base_no_weapon"].append([r["offset"], r["from_clip"], r["to_clip"]])
    # backpack-off: draw / holster actions of every weapon with and without the backpack-off overlay
    bo = {"set": BACKPACK_OFF, "set_remaps": [], "actions": {}, "changed": []}
    if BACKPACK_OFF in ex.db.sets:
        bo["set_remaps"] = [[r["offset"], r["from_clip"], r["to_clip"]] for r in ex.db.sets[BACKPACK_OFF]["remaps"]]
        for w in ("bow", "musket", "pistol", "unarmed"):
            for st in ("stand", "crouch"):
                mk = B["stance_selection_mode"][st]
                for key in ("grab", "equip", "holster", "holster_finish"):
                    spec = B["actions"][key]
                    row = {}
                    for label, extra in (("backpack_on", None), ("backpack_off", {"backpack": BACKPACK_OFF})):
                        sel = ex.selection(w, mk, extra)
                        clips = {}
                        for part, sname in (("partial", spec["state"]), ("twin", spec["twin"])):
                            s_ = ex.state(sname)
                            lv = ex.tree_leaves(s_["tree"])
                            if not lv:
                                continue
                            r = ex.build_role_from_id(sname, lv[0]["clip"], lv[0]["clip_id"], sel,
                                                      f"loadout.backpack.{w}/{st}/{key}/{part}", lv[0])
                            clips[part] = r.get("clip")
                            clips[part + "_chain"] = [[c["layer"], c["record_offset"], c["to"]] for c in r.get("chain", [])]
                        row[label] = clips
                    bo["actions"][f"{w}/{st}/{key}"] = row
                    if row["backpack_on"].get("partial") != row["backpack_off"].get("partial") or \
                            row["backpack_on"].get("twin") != row["backpack_off"].get("twin"):
                        bo["changed"].append(f"{w}/{st}/{key}")
    out["backpack_off"] = bo
    out["warnings"] = [w for w in ex.warnings if "unarmed" in w or "loadout." in w]
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write(json.dumps(out, indent=1, sort_keys=False) + "\n")
    print("LOADOUT GRAPH OK: %d unarmed roles, %d modes, backpack-off changes %d actions -> %s"
          % (len(out["roles"]), len(modes), len(out["backpack_off"]["changed"]), a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
