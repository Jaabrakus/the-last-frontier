#!/usr/bin/env python3
"""Renders the music's cues (tools/music/cues/) into audio/music/ and writes scripts/audio/music_manifest.gd.

    python3 tools/music/render.py                 every cue
    python3 tools/music/render.py giant_battle    the ones named
    python3 tools/music/render.py --bars 20-28 main_theme --out /tmp/x    a stretch, for a listen (no manifest)

A cue module has CUE (name, target loudness, and `loop`: (first bar, bar after the last) of the stretch the game loops)
and build() -> Score. A looped cue's file ends at the loop's end, the tail that rings past it laid over the loop's
start (so the seam carries on), and holds the loop in a RIFF smpl chunk (Godot's "Detect From WAV").
"""
from __future__ import annotations

import argparse
import importlib
import os
import sys
import time
import wave

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "cues"))
import orch  # noqa: E402

sys.path.insert(0, os.path.join(HERE, "..", "sfx"))
import dsp  # noqa: E402

OUT = os.path.join(ROOT, "audio", "music")
MANIFEST = os.path.join(ROOT, "scripts", "audio", "music_manifest.gd")
ORDER = ["main_theme", "explore_day", "explore_dusk", "explore_night", "giant_battle", "giant_upper_hand",
		"giant_lament"]


def cue_names() -> list:
	have = {f[:-3] for f in os.listdir(os.path.join(HERE, "cues")) if f.endswith(".py") and not f.startswith("_")}
	return [n for n in ORDER if n in have] + sorted(have - set(ORDER))


def render_cue(name: str, out_dir: str, bar_range: tuple | None = None) -> str:
	mod = importlib.import_module(name)
	cue = mod.CUE
	s = mod.build()
	t0 = time.time()
	loop = cue.get("loop")
	if bar_range:
		a, b = bar_range
		ta, tb = s.t(a), s.t(b)
		s.events = [e for e in s.events if ta - 0.05 <= e["t"] < tb]
		for e in s.events:
			e["t"] -= ta
		loop = None
	if loop and not bar_range:
		x, ls = render_loop(s, loop, cue.get("pre", 0))
	else:
		x = orch.render(s)
		ls = None
		env = np.abs(x).max(axis=1)
		last = int(np.nonzero(env > 10 ** (-70 / 20))[0][-1]) if np.any(env > 1e-5) else len(x)
		x = x[:last + 1]
		x = dsp.fade_out(x, 0.05)
	y = orch.master(x, cue["target"])
	os.makedirs(out_dir, exist_ok=True)
	path = os.path.join(out_dir, f"{name}.wav")
	if ls is not None:
		dsp.write_wav_loop(path, y.astype(np.float64), ls, len(y) - 1, sr=orch.SR)
	else:
		dsp.write_wav(path, y.astype(np.float64), sr=orch.SR)
	pk = 20 * np.log10(np.abs(y).max() + 1e-12)
	print(f"{name}: {len(y) / orch.SR:.1f} s, loudness {orch.loudness(y):.1f}, peak {pk:.1f} dB"
			f"{f', loop {ls / orch.SR:.2f}-{len(y) / orch.SR:.2f} s' if ls is not None else ''}"
			f" ({time.time() - t0:.0f} s) -> {os.path.relpath(path, ROOT)}", flush=True)
	return path


def render_loop(s: orch.Score, loop: tuple, pre: int) -> tuple:
	"""A looped cue: (audio, loop start frame). The loop is rendered alone, the tail ringing past its end laid over its
	start, so each pass carries on from the last. The intro (the bars before it) is rendered alone too; its last `pre`
	bars are the loop's own last bars (the intro's tail faded out under them), so coming in from the intro sounds just
	like coming round again. A swell into the loop goes at the loop's end (it wraps), not at its start."""
	ts, te = s.t(loop[0]), s.t(loop[1])
	ls, le = int(round(ts * orch.SR)), int(round(te * orch.SR))
	L = le - ls
	evs = s.events
	s.events = [dict(e, t=e["t"] - ts) for e in evs if e["t"] >= ts - 0.03]
	r = orch.render(s)
	body = r[:L].copy()
	tail = r[L:]
	k = min(len(tail), L)
	body[:k] += tail[:k]
	intro = np.zeros((ls, 2), np.float32)
	s.events = [e for e in evs if e["t"] < ts - 0.03]
	if s.events:
		ri = orch.render(s)[:ls]
		if pre:
			p0 = int(round(s.t(loop[0] - pre) * orch.SR))
			fade = np.ones(len(ri), np.float32)
			fade[p0:] = np.cos(np.linspace(0.0, np.pi / 2.0, len(ri) - p0, dtype=np.float32)) ** 2
			ri = ri * fade[:, None]
		intro[:len(ri)] += ri
	if pre:
		n = ls - int(round(s.t(loop[0] - pre) * orch.SR))
		intro[ls - n:] += body[L - n:L]
	s.events = evs
	return np.concatenate([intro, body]), ls


def write_manifest() -> None:
	lines = ["## Generated by tools/music/render.py: the music (audio/music/), each cue's tempo, bar and loop.",
			"##   path, bpm, beats (a bar), length (s), loop_start (s; -1 not looped: the loop runs to its end)",
			"", "const CUES := {"]
	for name in cue_names():
		path = os.path.join(OUT, f"{name}.wav")
		if not os.path.exists(path):
			continue
		mod = importlib.import_module(name)
		s = mod.build()
		with wave.open(path) as w:
			length = w.getnframes() / w.getframerate()
		loop = mod.CUE.get("loop")
		ls = s.t(loop[0]) if loop else -1.0
		lines.append(f'\t"{name}": {{"path": "res://audio/music/{name}.wav", "bpm": {s.bpm_at(loop[0] if loop else 0):.1f}, '
				f'"beats": {s.beats}, "length": {length:.3f}, "loop_start": {ls:.4f}}},')
	lines.append("}")
	with open(MANIFEST, "w") as f:
		f.write("\n".join(lines) + "\n")
	print(f"wrote {os.path.relpath(MANIFEST, ROOT)}")


def main() -> None:
	ap = argparse.ArgumentParser()
	ap.add_argument("cues", nargs="*")
	ap.add_argument("--bars", help="a-b: only those bars (a listen; no loop, no manifest)")
	ap.add_argument("--out", default=None)
	a = ap.parse_args()
	names = a.cues or cue_names()
	br = tuple(int(v) for v in a.bars.split("-")) if a.bars else None
	out = a.out or OUT
	for n in names:
		render_cue(n, out, br)
	if not br and out == OUT:
		write_manifest()


if __name__ == "__main__":
	main()
