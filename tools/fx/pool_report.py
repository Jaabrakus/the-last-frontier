#!/usr/bin/env python3
"""Read-only report on the imported Spellbreak pool (assets/fx/spellbreak): which files each switch can reach, what a trim
would save. It deletes and moves nothing (the one file it writes is the --trim-md list, under artifacts/).

  python3 -I tools/fx/pool_report.py [--list-trim] [--recompress-estimate] [--trim-md PATH]

Tiers (MB include each texture's .import and each glTF's .bin / .import):
  dormant   what the shipped switches reach today: every element off in data/bending/sb_fx/config.json -> only the files code
            loads by path (BendLooks.SB_BOLT_TEX / SB_BOLT_NOISE: the lightning restyle)
  wired     every effect a move/role of data/bending/sb_fx/<element>.json names (what turning the elements on could play)
  imported  everything in index.json (wired + 'unwired' rows + effects nothing names)
--list-trim prints, for the effects no element file wires, the files only they use (the safe-to-leave-out set). An effect that
no element file wires and that owns no file (all its files are wired effects' or the lightning restyle's) saves nothing, so it
is kept ("kept (own no file)"): its spec stays in index.json, which the tests and config.json's hide_materials read.
--recompress-estimate (needs Pillow) re-encodes every PNG in memory, lossless, and prints the saving; writes nothing.
--trim-md PATH writes the trim proposal as markdown (every effect no element file wires, the exact files only it uses with
their .import / .bin sidecars, sizes and the total saving; the unwired effects that own no file are listed apart, as kept).
A proposal for the owner: nothing is deleted or moved. Dropping the effects also means taking their rows out of index.json
(the importer has no remove mode yet) and out of SOURCE.md.
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
while not os.path.exists(os.path.join(ROOT, "project.godot")) and ROOT != "/":
    ROOT = os.path.dirname(ROOT)
POOL = os.path.join(ROOT, "assets", "fx", "spellbreak")
SB = os.path.join(ROOT, "data", "bending", "sb_fx")
LIGHTNING = ["assets/VFX/Textures/T_f_GenericLighting_F.png", "assets/VFX/Textures/T_f_SmokeHeight_Greyscale_Uncompressed.png"]


def sizes():
    out = {}
    for dp, _dn, fn in os.walk(os.path.join(POOL, "assets")):
        for f in fn:
            p = os.path.join(dp, f)
            out[os.path.relpath(p, POOL)] = os.path.getsize(p)
    return out


def with_sidecars(paths, sz):
    s = set()
    for p in paths:
        s.add(p)
        if p + ".import" in sz:
            s.add(p + ".import")
        if p.endswith(".gltf") and p[:-5] + ".bin" in sz:
            s.add(p[:-5] + ".bin")
    return s


def mb(paths, sz):
    s = with_sidecars(paths, sz)
    return sum(sz.get(x, 0) for x in s) / 1e6, len(s)


def write_trim_md(path, idx, never, spec_only, unwired, wired_files, files, sz, size_mb, n_files, imported, hide_mats=()):
    lines = ["# Spellbreak pool: trim proposal (nothing deleted or moved)", "",
             "Generated by `tools/fx/pool_report.py --trim-md`. **A proposal for the owner: no file under `assets/fx/spellbreak/` was "
             "deleted or moved.** The effects below are imported but no element file in `data/bending/sb_fx/` wires them "
             "(`unwired` = a tuner listed a row and left it out, with why; `NAMED NOWHERE` = no file names it). With every "
             "element switched off (the shipped state) the pool is dormant but for the lightning restyle's two textures, which "
             "the trim keeps.", "",
             "| | MB | files (with .import / .bin sidecars) |", "| --- | --- | --- |",
             "| the whole pool (`assets/`) | %.1f | %d |" % (sum(sz.values()) / 1e6, len(sz)),
             "| imported (index.json) | %.1f | %d |" % imported,
             "| **saved by the trim below** | **%.1f** | **%d** |" % (size_mb, n_files), "",
             "Also, without trimming anything: lossless PNG re-encode (`--recompress-estimate`, Pillow) is estimated at 21.7 MB.",
             "", "## What the trim touches", "",
             "To apply it: take the %d effects out of `index.json`, `materials.json` (their materials, meshes and `texture_alpha` "
             "rows) and `SOURCE.md`, then delete the files listed. `tests/fx/test_cascade_runtime.gd` spawns every effect in "
             "`index.json`, so it follows the index: it asks for at least every effect an element file wires (not a fixed "
             "count), and its fixtures are all wired effects (no test names a trimmed one). The %d unwired effects that own "
             "no file are **not** in the trim (see the end): their specs hold the materials `hide_materials` in "
             "`data/bending/sb_fx/config.json` names, and taking them out saves nothing. The one-off probes "
             "`tools/fx/review_r*.gd` name some trimmed effects (TornadoNewSimple, WindMBlast_FX, DashTrail_FX); they are "
             "not tests." % (len(never), len(spec_only)),
             "", "| Effect | Status | MB only it uses | Files only it uses |", "| --- | --- | --- | --- |"]
    total = set()
    for e in sorted(never):
        ex = with_sidecars(files([e]) - wired_files - set(LIGHTNING), sz)
        total |= ex
        tag = "unwired" if e in unwired else "NAMED NOWHERE"
        lines.append("| `%s` | %s | %.2f | %s |" % (e, tag, sum(sz.get(x, 0) for x in ex) / 1e6,
                                                    ", ".join("`%s`" % x for x in sorted(ex)) or "none (spec only)"))
    lines += ["", "Total: %d files, %.1f MB (a file two trimmed effects share is counted once above only if no wired effect uses "
              "it; it appears under each trimmed effect that names it)." % (len(total), sum(sz.get(x, 0) for x in total) / 1e6), ""]
    lines += ["## Kept: unwired, but they own no file", "",
              "%d effects no element file wires whose every file is a wired effect's (or the lightning restyle's): dropping them "
              "frees nothing. `hide_materials` in `data/bending/sb_fx/config.json` is checked against the imported effects' "
              "materials (`tests/fx/test_sb_fx_bridge.gd`), and some of those materials live only in these specs. Leave them in "
              "`index.json`." % len(spec_only), "", "| Effect | Status | `hide_materials` entries it holds |", "| --- | --- | --- |"]
    for e in sorted(spec_only):
        held = [m for m in idx[e].get("materials", []) if m in hide_mats]
        lines.append("| `%s` | %s | %s |" % (e, "unwired" if e in unwired else "NAMED NOWHERE",
                                              ", ".join("`%s`" % m for m in held) or "none"))
    lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--list-trim", action="store_true")
    ap.add_argument("--recompress-estimate", action="store_true")
    ap.add_argument("--trim-md", metavar="PATH")
    a = ap.parse_args()
    idx = json.load(open(os.path.join(POOL, "index.json")))["effects"]
    cfg = json.load(open(os.path.join(SB, "config.json")))
    sz = sizes()
    wired, unwired = {}, {}
    for el in ("earth", "water", "fire", "air"):
        doc = json.load(open(os.path.join(SB, el + ".json")))
        for _k, roles in doc.get("moves", {}).items():
            for _r, e in roles.items():
                if isinstance(e, dict) and e.get("effect"):
                    wired.setdefault(e["effect"], set()).add(el)
        for u in doc.get("unwired", []):
            if u.get("effect"):
                unwired.setdefault(u["effect"], set()).add(el)
    on = [el for el, v in cfg.get("elements", {}).items() if v] if cfg.get("enabled", False) else []

    def files(ids):
        s = set()
        for e in ids:
            s |= set(idx[e]["textures"]) | set(idx[e]["meshes"])
        return s

    all_files = files(idx)
    wired_files = files(wired)
    on_files = files([e for e, els in wired.items() if any(x in on for x in els)])
    print("switches in config.json: master %s, elements on: %s" % (cfg.get("enabled"), on or "none"))
    print("effects: imported %d, wired %d, 'unwired' only %d, named nowhere %d" % (
        len(idx), len(wired), len([e for e in unwired if e not in wired]), len([e for e in idx if e not in wired and e not in unwired])))
    t = mb(all_files | set(LIGHTNING), sz)
    print("pool total (assets/): %.1f MB in %d files" % (sum(sz.values()) / 1e6, len(sz)))
    print("  imported (index.json)        %6.1f MB  %3d files" % t)
    print("  wired (an element file names) %6.1f MB  %3d files" % mb(wired_files | set(LIGHTNING), sz))
    print("  reached by the shipped switches %5.1f MB  %3d files  (+ the lightning restyle's 2 textures)" % mb(on_files | set(LIGHTNING), sz))
    print("  lightning restyle only        %6.1f MB  %3d files" % mb(set(LIGHTNING), sz))
    stray = [p for p in sz if not p.endswith(".import") and not p.endswith(".bin") and p not in all_files and p not in LIGHTNING]
    print("  files in assets/ no index row names: %d" % len(stray))
    unwired_all = [e for e in idx if e not in wired]
    # an effect that owns no file frees nothing when dropped, and its spec still serves the tests and hide_materials: kept
    never = [e for e in unwired_all if files([e]) - wired_files - set(LIGHTNING)]
    spec_only = [e for e in unwired_all if e not in never]
    only_never = files(never) - wired_files - set(LIGHTNING)
    size_mb, n_files = mb(only_never, sz)
    print("effects no element file wires: %d, %d of them own files -> files only they use: %d (%.1f MB); %d kept (own no file)" % (
        len(unwired_all), len(never), n_files, size_mb, len(spec_only)))
    if a.list_trim:
        for e in sorted(never):
            tag = "unwired-listed" if e in unwired else "NAMED NOWHERE"
            ex = files([e]) - wired_files - set(LIGHTNING)
            print("  %-60s %-15s %5.1f MB exclusive (%d files)" % (e.split("/")[-1], tag, mb(ex, sz)[0], len(ex)))
        for e in sorted(spec_only):
            tag = "unwired-listed" if e in unwired else "NAMED NOWHERE"
            print("  %-60s %-15s kept (own no file)" % (e.split("/")[-1], tag))
    if a.trim_md:
        write_trim_md(a.trim_md, idx, never, spec_only, unwired, wired_files, files, sz, size_mb, n_files, t, cfg.get("hide_materials", []))
    if a.recompress_estimate:
        try:
            import io
            from PIL import Image
        except ImportError:
            print("Pillow is not installed: no estimate")
            return 0
        before = after = 0
        for p in sz:
            if p.endswith(".png"):
                im = Image.open(os.path.join(POOL, p))
                im.load()
                b = io.BytesIO()
                im.save(b, "PNG", optimize=True, compress_level=9)
                before += sz[p]
                after += min(sz[p], b.tell())
        print("lossless PNG re-encode (optimize, same modes): %.1f MB -> %.1f MB (saves %.1f MB)" % (before / 1e6, after / 1e6, (before - after) / 1e6))
    return 0


if __name__ == "__main__":
    sys.exit(main())
