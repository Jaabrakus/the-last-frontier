# ---------------------------------------------------------------- colour

def hex_srgb(h):
    h = h.lstrip("#")
    return np.array([int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)], np.float32)


def s2l(c):
    c = np.asarray(c, np.float32)
    return np.where(c <= 0.04045, c / 12.92, ((np.maximum(c, 0) + 0.055) / 1.055) ** 2.4).astype(np.float32)


def l2s(c):
    c = np.clip(np.asarray(c, np.float32), 0.0, 1.0)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * np.power(c, 1.0 / 2.4) - 0.055).astype(np.float32)


def lin(h):
    """Hex -> linear RGB."""
    return s2l(hex_srgb(h))


def ramp(name, zone="r1"):
    """A material's 4-stop ramp (dark, mid, light, accent) as linear RGB, shape (4, 3)."""
    return np.stack([lin(h) for h in PAL["albedo"][zone][name]])


def direction(name):
    return PAL["directions"][name]


def mix(a, b, t):
    return a + (b - a) * t


def ramp_at(r4, t):
    """A colour along the ramp's dark (t=0) -> mid (0.5) -> light (1) span, blended in sRGB (painter's mixing)."""
    t = float(min(max(t, 0.0), 1.0))
    s = l2s(r4[:3])
    if t < 0.5:
        c = mix(s[0], s[1], t * 2.0)
    else:
        c = mix(s[1], s[2], t * 2.0 - 1.0)
    return s2l(c)


def ramp_map(r4, t):
    """ramp_at for an array of t (any shape) -> linear RGB (..., 3)."""
    t = np.clip(np.asarray(t, np.float32), 0.0, 1.0)[..., None]
    s = l2s(r4[:3])
    lo = s[0] + (s[1] - s[0]) * np.clip(t * 2.0, 0, 1)
    hi = s[1] + (s[2] - s[1]) * np.clip(t * 2.0 - 1.0, 0, 1)
    return s2l(np.where(t < 0.5, lo, hi))


def jitter(c_lin, dv=0.0, dh=0.0, ds=0.0):
    """Shift a linear colour by value (fraction), hue (degrees) and saturation (fraction), in sRGB HSV."""
    s = l2s(c_lin)
    h, sa, v = colorsys.rgb_to_hsv(*[float(x) for x in s])
    h = (h + dh / 360.0) % 1.0
    sa = min(max(sa * (1.0 + ds), 0.0), 1.0)
    v = min(max(v * (1.0 + dv), 0.0), 1.0)
    return s2l(np.array(colorsys.hsv_to_rgb(h, sa, v), np.float32))


def rgb_to_hsv(rgb):
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    mx = rgb.max(-1)
    mn = rgb.min(-1)
    d = mx - mn
    m = d > 1e-6
    dd = np.where(m, d, 1.0)
    rc, gc, bc = (mx - r) / dd, (mx - g) / dd, (mx - b) / dd
    h = np.where(r == mx, bc - gc, np.where(g == mx, 2.0 + rc - bc, 4.0 + gc - rc))
    h = np.where(m, (h / 6.0) % 1.0, 0.0)
    s = np.where(mx > 1e-6, d / np.maximum(mx, 1e-6), 0.0)
    return np.stack([h, s, mx], -1)


def hsv_to_rgb(hsv):
    h, s, v = hsv[..., 0] % 1.0, np.clip(hsv[..., 1], 0, 1), np.clip(hsv[..., 2], 0, 1)
    i = np.floor(h * 6.0)
    f = h * 6.0 - i
    p, q, t = v * (1 - s), v * (1 - s * f), v * (1 - s * (1 - f))
    i = i.astype(np.int32) % 6
    r = np.choose(i, [v, q, p, p, t, v])
    g = np.choose(i, [t, v, v, q, p, p])
    b = np.choose(i, [p, p, t, v, v, q])
    return np.stack([r, g, b], -1)


def luma(c):
    return 0.2126 * c[..., 0] + 0.7152 * c[..., 1] + 0.0722 * c[..., 2]


# ---------------------------------------------------------------- fields

def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def periodic_field(h, w, rng, kmax=2, kmin=1, slope=1.0):
    """Tileable smooth field in about [-1, 1]: a sum of whole-period waves (|k| between kmin and kmax per axis)."""
    y = np.arange(h, dtype=np.float32)[:, None] / h
    x = np.arange(w, dtype=np.float32)[None, :] / w
    f = np.zeros((h, w), np.float32)
    for ky in range(-kmax, kmax + 1):
        for kx in range(0, kmax + 1):
            k = max(abs(kx), abs(ky))
            if k < kmin or (kx == 0 and ky <= 0):
                continue
            a = rng.normal() / (k ** slope)
            p = rng.uniform(0, 2 * math.pi)
            cx = np.cos(2 * math.pi * kx * x + p)
            sx = np.sin(2 * math.pi * kx * x + p)
            cy = np.cos(2 * math.pi * ky * y)
            sy = np.sin(2 * math.pi * ky * y)
            f += a * (cy * cx - sy * sx)
    m = np.abs(f).max()
    return f / m if m > 0 else f


def periodic_1d(n, rng, kmax=6, kmin=1):
    x = np.arange(n, dtype=np.float32) / n
    f = np.zeros(n, np.float32)
    for k in range(kmin, kmax + 1):
        f += rng.normal() / k * np.cos(2 * math.pi * k * x + rng.uniform(0, 2 * math.pi))
    m = np.abs(f).max()
    return f / m if m > 0 else f


_gk = {}


def blur(a, sigma):
    """Gaussian blur on the torus (FFT). a: (h, w) or (h, w, c)."""
    if sigma <= 0:
        return a
    h, w = a.shape[:2]
    key = (h, w, round(float(sigma), 3))
    if key not in _gk:
        fy = np.fft.fftfreq(h)[:, None]
        fx = np.fft.rfftfreq(w)[None, :]
        _gk[key] = np.exp(-2.0 * math.pi ** 2 * sigma ** 2 * (fx ** 2 + fy ** 2)).astype(np.float32)
        if len(_gk) > 24:
            _gk.pop(next(iter(_gk)))
    g = _gk[key]
    if a.ndim == 2:
        return np.fft.irfft2(np.fft.rfft2(a) * g, s=(h, w)).astype(np.float32)
    return np.stack([np.fft.irfft2(np.fft.rfft2(a[..., i]) * g, s=(h, w)) for i in range(a.shape[2])],
                    -1).astype(np.float32)


def blur_clamped(a, sigma):
    """Gaussian blur for non-tiling images (cards): pad by reflection, blur, crop."""
    if sigma <= 0:
        return a
    p = int(math.ceil(sigma * 3)) + 1
    pad = ((p, p), (p, p)) + (((0, 0),) if a.ndim == 3 else ())
    b = blur(np.pad(a, pad, mode="reflect"), sigma)
    return b[p:-p, p:-p]


# ---------------------------------------------------------------- canvas

class Canvas:
    """A torus canvas (wrap=True) or a card (wrap=False): linear colour, stroke height, big-stroke mask, optional
    alpha. Brush strokes carry bristle streaks by default (bristle=0 for a flat fill)."""

    def __init__(self, h, w, tile_m, seed, ramp4, alpha=False, wrap=True, bristle=0.35, streak=0.06):
        self.h, self.w = h, w
        self.ppm = w / tile_m
        self.rng = np.random.default_rng(seed)
        self.ramp = ramp4
        self.col = np.zeros((h, w, 3), np.float32)
        self.col[:] = ramp4[1]
        self.ht = np.zeros((h, w), np.float32)
        self.big = np.zeros((h, w), np.float32)
        self.alpha = np.zeros((h, w), np.float32) if alpha else None
        self.wrap = wrap
        self.bristle = bristle
        self.streak = streak
        self.lf_v = periodic_field(h, w, self.rng, 2, 1)
        self.lf_h = periodic_field(h, w, self.rng, 2, 1)
        self.lf_s = periodic_field(h, w, self.rng, 2, 1)

    def px(self, metres):
        return metres * self.ppm

    # -- base -------------------------------------------------------------
    def base(self, dv=0.08, dh=5.0, ds=0.10, color=None):
        """Fill with `mid` (or color) and the low-frequency variation (value, hue, saturation)."""
        c = self.ramp[1] if color is None else color
        hsv = rgb_to_hsv(np.broadcast_to(l2s(c), (self.h, self.w, 3)).copy())
        hsv[..., 0] = (hsv[..., 0] + self.lf_h * dh / 360.0) % 1.0
        hsv[..., 1] = np.clip(hsv[..., 1] * (1.0 + ds * self.lf_s), 0, 1)
        hsv[..., 2] = np.clip(hsv[..., 2] * (1.0 + dv * self.lf_v), 0, 1)
        self.col = s2l(hsv_to_rgb(hsv))

    def apply_lf(self, dv=0.08, dh=5.0, ds=0.10):
        """The low-frequency value / hue / saturation variation applied over what is painted so far."""
        hsv = rgb_to_hsv(l2s(self.col))
        hsv[..., 0] = (hsv[..., 0] + self.lf_h * dh / 360.0) % 1.0
        hsv[..., 1] = np.clip(hsv[..., 1] * (1.0 + ds * self.lf_s), 0, 1)
        hsv[..., 2] = np.clip(hsv[..., 2] * (1.0 + dv * self.lf_v), 0, 1)
        self.col = s2l(hsv_to_rgb(hsv))

    def warp(self, amp_px, kmax=12, kmin=4):
        """A tileable smooth displacement field (float px: wy, wx) for warping cell maps into natural cracks."""
        wx = periodic_field(self.h, self.w, self.rng, kmax, kmin, slope=0.6) * amp_px
        wy = periodic_field(self.h, self.w, self.rng, kmax, kmin, slope=0.6) * amp_px
        return wy.astype(np.float32), wx.astype(np.float32)

    def vary(self, c, x, y, dv=0.08, dh=5.0, ds=0.10, jit=0.03):
        """A dab colour: the colour shifted by the low-frequency fields at the dab, plus +-jit value."""
        iy, ix = int(y) % self.h, int(x) % self.w
        return jitter(c, dv * self.lf_v[iy, ix] + self.rng.uniform(-jit, jit), dh * self.lf_h[iy, ix],
                      ds * self.lf_s[iy, ix])

    def pick(self, weights=(0.20, 0.45, 0.30, 0.05)):
        """A colour from the ramp: dark / mid / light / accent by weight, then slid a little along the ramp, so
        strokes land on a continuous span of the hue family instead of four flat stops."""
        k = self.rng.choice(4, p=np.array(weights) / sum(weights))
        if k == 3:
            return self.ramp[3]
        t = {0: 0.0, 1: 0.5, 2: 1.0}[k] + self.rng.normal(0.0, 0.12)
        return ramp_at(self.ramp, t)

    def tone(self, t, x=None, y=None, jit=0.03):
        """ramp_at(t) with the low-frequency variation at (x, y)."""
        c = ramp_at(self.ramp, t)
        return c if x is None else self.vary(c, x, y, jit=jit)

    # -- brush ------------------------------------------------------------
    def _patch(self, cx, cy, R):
        x0, y0 = int(math.floor(cx - R)), int(math.floor(cy - R))
        xs = np.arange(x0, x0 + 2 * R + 2)
        ys = np.arange(y0, y0 + 2 * R + 2)
        if self.wrap:
            xs = xs[:self.w]
            ys = ys[:self.h]
        else:
            xs = xs[(xs >= 0) & (xs < self.w)]
            ys = ys[(ys >= 0) & (ys < self.h)]
            if len(xs) == 0 or len(ys) == 0:
                return None
        dx = (xs + 0.5 - cx)[None, :].astype(np.float32)
        dy = (ys + 0.5 - cy)[:, None].astype(np.float32)
        return np.ix_(ys % self.h, xs % self.w), dx, dy

    @staticmethod
    def _frame(dx, dy, rx, ry, ang, bend=0.0):
        ca, sa = math.cos(ang), math.sin(ang)
        u = dx * ca + dy * sa
        v = -dx * sa + dy * ca
        if bend:
            v = v - bend * (u / rx) ** 2 * ry
        return u, v

    @staticmethod
    def _shape(u, v, rx, ry, power=2.0, taper=0.0, wob=0.0, wp=(0.0, 0.0), poly=None):
        ryy = ry
        if taper:
            t = np.clip((u / rx + 1.0) * 0.5, 0.0, 1.0)  # 0 at the -u end, 1 at the +u end
            ryy = ry * np.maximum(1.0 - taper * t, 0.05)
        if poly is not None:
            qu, qv = u / rx, v / ryy
            r = None
            for (nx, ny, d) in poly:
                e = (nx * qu + ny * qv) / d
                r = e if r is None else np.maximum(r, e)
            r = np.maximum(r, 0.0)
        else:
            r = (np.abs(u / rx) ** power + np.abs(v / ryy) ** power) ** (1.0 / power)
        if wob:
            th = np.arctan2(v / ry, u / rx)
            r = r / (1.0 + wob * (0.6 * np.sin(3 * th + wp[0]) + 0.4 * np.sin(5 * th + wp[1])))
        return r

    def _bristles(self, u, v, rx, ry, amt, dry):
        """A per-stroke bristle profile across the stroke (v), streaking along it (u). Returns (alpha multiplier,
        streak value offset in [-0.5, 0.5])."""
        rng = self.rng
        vn = v / max(ry, 1e-3)
        un = np.clip((u / max(rx, 1e-3) + 1.0) * 0.5, 0.0, 1.0)
        # bristles about 2.5-6 px apart, so wide strokes show many fine streaks and thin ones a few
        nb = max(ry * 2.0 / rng.uniform(2.5, 6.0), 2.0)
        p = np.zeros_like(vn)
        tot = 0.0
        for k in range(4):
            f = nb * rng.uniform(0.25, 1.0) * (0.5 ** (k * 0.5))
            a = 1.0 / (k + 1)
            p = p + a * np.sin(vn * f * math.pi + rng.uniform(0, 6.283) + 0.6 * np.sin(un * rng.uniform(1, 3) * 3.1))
            tot += a
        p = 0.5 + 0.5 * p / tot
        th = dry * un ** 1.6
        m = smoothstep(th - 0.16, th + 0.16, p)
        return (1.0 - amt) + amt * m, p - 0.5

    def dab(self, cx, cy, rx, ry, ang, color, h_add=0.0, big=False, edge=0.7, power=2.0, taper=0.0, wob=0.08,
            opacity=1.0, bend=0.0, alpha_add=False, hmode="layer", poly=None, bristle=None, dry=0.35, color2=None,
            streak=None):
        """One brush stroke along `ang` (rx along, ry across): firm painter's edge (alpha = 1 - smoothstep(edge, 1,
        r)), bristle streaks and a dry tail, loaded with `color` at its head blending to `color2` at its tail."""
        R = int(math.ceil(max(rx, ry) * (1.0 + wob + abs(bend)) + 2))
        p = self._patch(cx, cy, R)
        if p is None:
            return
        ix, dx, dy = p
        wp = (self.rng.uniform(0, 6.283), self.rng.uniform(0, 6.283))
        u, v = self._frame(dx, dy, rx, ry, ang, bend)
        r = self._shape(u, v, rx, ry, power, taper, wob, wp, poly)
        a = (1.0 - smoothstep(edge, 1.0, r)) * opacity
        if not a.any():
            return
        bam = self.bristle if bristle is None else bristle
        st = self.streak if streak is None else streak
        col = np.asarray(color, np.float32)
        if bam > 0 or st > 0:
            bm, sv = self._bristles(u, v, rx, ry, bam, dry)
            a = a * bm
            colp = col[None, None, :] * (1.0 + st * 2.0 * sv[..., None])
        else:
            colp = np.broadcast_to(col, a.shape + (3,))
        if color2 is not None:
            t = np.clip((u / rx + 1.0) * 0.5, 0.0, 1.0)[..., None]
            colp = colp + (np.asarray(color2, np.float32) * (colp / np.maximum(col, 1e-4)) - colp) * t
        c = self.col[ix]
        self.col[ix] = c + (colp - c) * a[..., None]
        if h_add:
            hh = self.ht[ix]
            prof = np.clip(1.0 - r * r, 0.0, 1.0)
            if hmode == "add":
                self.ht[ix] = hh + h_add * prof * a
            else:
                inside = a > 0.5
                base = float(hh[inside].mean()) if inside.any() else float(hh.mean())
                tgt = base + h_add * (0.55 + 0.45 * prof)
                self.ht[ix] = hh + (tgt - hh) * a
        if big:
            self.big[ix] = np.maximum(self.big[ix], a)
        if self.alpha is not None and alpha_add:
            self.alpha[ix] = np.maximum(self.alpha[ix], np.clip(a * 1.6, 0, 1) if bam > 0 else a)
        return a

    def stroke3(self, cx, cy, rx, ry, ang, body, dark, light, up=(0.0, -1.0), h_add=0.5, power=2.0, taper=0.0,
                wob=0.08, edge=0.7, dark_off=0.15, light_off=0.20, light_amt=0.85, dark_amt=0.9, bend=0.0,
                alpha_add=False, shade=0.0, opacity=1.0, poly=None, bristle=None, dry=0.25, streak=None):
        """A medium stroke painted three times: the dark copy offset down (its occlusion), the body, and a light
        sliver on its top edge (the body minus a copy of itself shifted away from `up`). The body carries bristle
        streaks; `shade` darkens it toward its side away from `up` (a painted rounded form)."""
        R = int(math.ceil(max(rx, ry) * (1.3 + wob + abs(bend)) + 2))
        p = self._patch(cx, cy, R)
        if p is None:
            return
        ix, dx, dy = p
        rad = min(rx, ry)
        ux, uy = up
        wp = (self.rng.uniform(0, 6.283), self.rng.uniform(0, 6.283))

        def sh(ox, oy):
            uu, vv = self._frame(dx - ox, dy - oy, rx, ry, ang, bend)
            return self._shape(uu, vv, rx, ry, power, taper, wob, wp, poly), uu, vv

        r_b, u_b, v_b = sh(0.0, 0.0)
        r_d, _, _ = sh(-ux * dark_off * rad * 1.6, -uy * dark_off * rad * 1.6)
        r_s, _, _ = sh(-ux * light_off * rad, -uy * light_off * rad)
        a_b = (1.0 - smoothstep(edge, 1.0, r_b)) * opacity
        a_d = (1.0 - smoothstep(edge * 0.8, 1.0, r_d)) * dark_amt * opacity
        a_l = a_b * smoothstep(edge, 1.0, r_s) * light_amt
        bam = self.bristle if bristle is None else bristle
        st = self.streak if streak is None else streak
        sv = 0.0
        if bam > 0 or st > 0:
            bm, sv = self._bristles(u_b, v_b, rx, ry, bam * 0.7, dry)
            a_b = a_b * bm
            a_l = a_l * bm
            sv = sv[..., None]
        c = self.col[ix]
        c = c + (np.asarray(dark, np.float32) - c) * a_d[..., None]
        bc = np.asarray(body, np.float32)[None, None, :] * (1.0 + st * 2.0 * sv)
        if shade:
            t = np.clip(-(dx * ux + dy * uy) / max(rad, 1e-3) / max(rx / rad, 1.0), -1.0, 1.0)
            k = smoothstep(-0.3, 1.0, t)[..., None] * shade
            bc = bc * (1.0 - k) + np.asarray(dark, np.float32)[None, None, :] * k
        c = c + (bc - c) * a_b[..., None]
        c = c + (np.asarray(light, np.float32) - c) * a_l[..., None]
        self.col[ix] = c
        if h_add:
            hh = self.ht[ix]
            inside = a_b > 0.5
            base = float(hh[inside].mean()) if inside.any() else float(hh.mean())
            prof = np.clip(1.0 - r_b * r_b, 0.0, 1.0)
            self.ht[ix] = hh + (base + h_add * (0.55 + 0.45 * prof) - hh) * a_b
        if self.alpha is not None and alpha_add:
            self.alpha[ix] = np.maximum(self.alpha[ix], np.clip(np.maximum(a_b, a_d) * 1.4, 0, 1))

    def path(self, pts, width, color, color2=None, opacity=1.0, edge=0.6, bristle=None, dry=0.4, taper=(0.3, 0.8),
             h_add=0.0, alpha_add=False, step=0.5, streak=None):
        """A long brush stroke along a polyline (pixels): overlapping dabs every `step` x width, tapering at both
        ends; the paint runs dry toward the end."""
        pts = np.asarray(pts, np.float32)
        seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
        L = float(seg.sum())
        if L < 1e-3:
            return
        n = max(int(L / max(width * step, 1.0)), 2)
        cum = np.concatenate([[0], np.cumsum(seg)])
        for i in range(n):
            s = (i + 0.5) / n * L
            j = min(int(np.searchsorted(cum, s) - 1), len(seg) - 1)
            j = max(j, 0)
            f = (s - cum[j]) / max(seg[j], 1e-6)
            p = pts[j] + (pts[j + 1] - pts[j]) * f
            d = pts[j + 1] - pts[j]
            ang = math.atan2(d[1], d[0])
            t = s / L
            w = width * min(1.0, (t / max(taper[0], 1e-3)) ** 0.5 if t < taper[0] else 1.0)
            if t > taper[1]:
                w *= max(1.0 - (t - taper[1]) / (1.0 - taper[1]), 0.15)
            c = color if color2 is None else mix(np.asarray(color), np.asarray(color2), t)
            self.dab(p[0], p[1], max(width * step * 1.4, w * 0.6), w * 0.5, ang, c, opacity=opacity, edge=edge,
                     bristle=bristle, dry=dry * t, wob=0.03, h_add=h_add, hmode="add", alpha_add=alpha_add,
                     streak=streak)

    # -- passes -----------------------------------------------------------
    def cavity(self, k=0.42, cool=AO_ROCK, sigma_frac=1 / 48.0, gamma=0.8):
        """Painted AO: cavity = blur(height) - height, darkened toward a cool dark."""
        bl = blur(self.ht, self.w * sigma_frac) if self.wrap else blur_clamped(self.ht, self.w * sigma_frac)
        cav = np.clip(bl - self.ht, 0.0, None)
        q = np.percentile(cav, 99.0)
        cav = np.clip(cav / max(q, 1e-6), 0.0, 1.0) ** gamma
        tgt = mix(self.ramp[0], lin(cool), 0.5)
        self.col = mix(self.col, np.broadcast_to(tgt, self.col.shape), (cav * k)[..., None])
        return cav

    def edge_light(self, amt=0.18, sigma=1.5, up=(0, -1)):
        """Lighten where the stroke height steps up toward the light (rims of slabs, plank edges)."""
        hb = blur(self.ht, sigma)
        ux, uy = up
        sh = np.roll(np.roll(hb, int(round(-uy * 2)), 0), int(round(-ux * 2)), 1)
        d = np.clip(hb - sh, 0.0, None)
        q = np.percentile(d, 99.0)
        e = np.clip(d / max(q, 1e-6), 0.0, 1.0)
        e = blur(e, 1.0)
        self.col = mix(self.col, np.broadcast_to(self.ramp[2], self.col.shape), (e * amt)[..., None])
        return e

    def finish(self, value_target=None, clamp=True, unsharp=0.4, soft=0.6, span_pad=(0.85, 1.12), squint=0.2):
        """Blur 0.6 px, unsharp-mask at 1/32 of the tile, keep every pixel's value inside the ramp's span (luminance,
        not per channel, so accent hues survive), limit the squint blobs, hit the value budget."""
        bl = blur if self.wrap else blur_clamped
        c = np.clip(bl(self.col, soft), 1e-4, 1.0)
        # unsharp mask on luminance only (a thin dark line must not overshoot into a pure hue)
        y0 = luma(c)
        y1 = np.clip(y0 + unsharp * (y0 - bl(y0, self.w / 64.0)), y0 * 0.5, y0 * 1.6 + 0.01)
        c = np.clip(c * (y1 / np.maximum(y0, 1e-5))[..., None], 0.002, 1.0)
        if clamp:
            ly = luma(c)
            lo = float(luma(self.ramp[:3]).min()) * span_pad[0]
            hi = min(float(luma(self.ramp).max()) * span_pad[1], 0.97)
            ly2 = np.clip(ly, lo, hi)
            c = c * (ly2 / np.maximum(ly, 1e-5))[..., None]
        c = np.clip(c, 0.004, 0.985)
        if value_target is not None:
            c = hit_value(c, value_target)
        if squint and self.wrap:
            c = limit_squint(c, squint, self.w / 40.0)
            if value_target is not None:
                c = hit_value(c, value_target)
        self.col = c
        return c

    def rgba(self, alpha=None):
        rgb = l2s(self.col)
        a = self.alpha if alpha is None else alpha
        if a is None:
            return to_u8(rgb)
        return to_u8(np.concatenate([rgb, np.clip(a, 0, 1)[..., None]], -1))


def voronoi(h, w, pts, sx=1.0, sy=1.0, reach=None, wrap=True, warp=None):
    """Periodic (torus) Voronoi of pts [(x, y), ...] under the metric sqrt((dx sx)^2 + (dy sy)^2): returns the
    nearest cell's index, the nearest distance d1 and the second-nearest d2 (so (d2 - d1) / 2 is roughly the
    distance to the cell's border). Each site only touches a window of `reach` px around it. `warp` = (wy, wx)
    float offset fields (px) displace every pixel's position smoothly, so cell borders wander like natural cracks."""
    pts = np.asarray(pts, np.float32)
    n = len(pts)
    if reach is None:
        reach = 3.0 * math.sqrt(h * w / max(n, 1)) / min(sx, sy)
    R = int(min(reach, max(h, w) / 2 - 1))
    big = np.float32(1e9)
    d1 = np.full((h, w), big, np.float32)
    d2 = np.full((h, w), big, np.float32)
    idx = np.zeros((h, w), np.int32)
    for i, (cx, cy) in enumerate(pts):
        x0, y0 = int(math.floor(cx)) - R, int(math.floor(cy)) - R
        xs = np.arange(x0, x0 + 2 * R + 1)
        ys = np.arange(y0, y0 + 2 * R + 1)
        if wrap:
            xs, ys = xs[:w], ys[:h]
        else:
            xs = xs[(xs >= 0) & (xs < w)]
            ys = ys[(ys >= 0) & (ys < h)]
        ix = np.ix_(ys % h, xs % w)
        dx = ((xs + 0.5 - cx) * sx)[None, :].astype(np.float32)
        dy = ((ys + 0.5 - cy) * sy)[:, None].astype(np.float32)
        if warp is not None:
            dx = dx + warp[1][ix] * sx
            dy = dy + warp[0][ix] * sy
        d = np.sqrt(dx * dx + dy * dy)
        a1, a2, ai = d1[ix], d2[ix], idx[ix]
        closer = d < a1
        a2 = np.where(closer, a1, np.minimum(a2, d))
        a1 = np.where(closer, d, a1)
        ai = np.where(closer, i, ai)
        d1[ix], d2[ix], idx[ix] = a1, a2, ai
    return idx, d1, d2


def random_poly(rng, n=(4, 7), jitter=0.25, chamfer=0.0):
    """A random convex polygon in the unit frame, as half-planes (nx, ny, d): r = max(n.q / d)."""
    k = int(rng.integers(n[0], n[1] + 1))
    base = rng.uniform(0, 2 * math.pi)
    angs = np.sort((base + np.arange(k) * 2 * math.pi / k + rng.uniform(-jitter, jitter, k) * 2 * math.pi / k)
                   % (2 * math.pi))
    rad = rng.uniform(1.0 - jitter * 0.5, 1.0, k)
    pts = np.stack([np.cos(angs) * rad, np.sin(angs) * rad], -1)
    pts /= np.abs(pts).max(0)
    planes = []
    for i in range(k):
        a, b = pts[i], pts[(i + 1) % k]
        e = b - a
        nrm = np.array([e[1], -e[0]])
        nrm /= max(np.linalg.norm(nrm), 1e-9)
        d = float(nrm @ a)
        if d < 0:
            nrm, d = -nrm, -d
        planes.append((float(nrm[0]), float(nrm[1]), max(d, 0.05)))
    return planes


def limit_squint(c_lin, lim, sigma):
    """Soft-limit the low-frequency value (sRGB) to mean +- lim (tanh), keeping the detail on top."""
    srgb = l2s(c_lin)
    v = srgb.mean(-1)
    lp = blur(v, sigma)
    m = float(lp.mean())
    lp2 = m + lim * np.tanh((lp - m) / lim)
    out = np.clip(srgb + (lp2 - lp)[..., None], 0.0, 1.0)
    return np.clip(s2l(out), 0.004, 0.985)


def hit_value(c_lin, target, iters=24):
    """Scale linear colour so the sRGB mean value lands on target (bisection on a linear gain)."""
    lo, hi = 0.3, 3.0
    for _ in range(iters):
        g = 0.5 * (lo + hi)
        m = float(l2s(np.clip(c_lin * g, 0, 0.985)).mean())
        if m < target:
            lo = g
        else:
            hi = g
    return np.clip(c_lin * 0.5 * (lo + hi), 0.004, 0.985)


def to_u8(a):
    return np.clip(np.round(a * 255.0), 0, 255).astype(np.uint8)


