"""Thủy Vân painter core (look builder PAINT): a deterministic numpy brush engine for hand-painted tiling textures.

The style guide (docs/thuyvan/plan/look/style_guide.md, section 3.2) is the recipe this module implements:

    ramp -> base + low-frequency variation (periods 1 and 1/2 of the tile) -> big brush strokes (firm edge, bristle
    streaks, two-colour loading, flow field) -> medium strokes painted three times (dark copy under, body, light
    sliver on top) -> stroke height map -> cavity AO toward a cool dark -> edge highlight (rock, wood) -> accents ->
    0.6 px blur + unsharp mask -> clamp to the ramp's value span -> value budget -> squint and 3 x 3 tiling check.

Version 2 (2026-10-06, after the first pass read as flat vector stickers): every dab is a BRUSH STROKE, not a flat
fill. A stroke carries a per-stroke bristle profile across its width (paint streaks along it, a dry-brush break-up
toward its tail), is loaded with two neighbouring colours that blend along its length, and lands at partial opacity
so layers glaze into each other the way a hand-painted texture does. Colours are picked continuously along the
material's ramp (dark -> mid -> light), not from four flat stops.

Everything is painted on a torus (every dab wraps), in linear float, with fixed seeds: a texture rebuilds bit for bit.
Colours come only from tools/thuyvan_art/paint/palettes.json (a verbatim copy of docs/thuyvan/plan/look/palettes.json,
generated by palettes.py); nobody retypes hex values. No photographs, no external images: everything is our own.
"""
