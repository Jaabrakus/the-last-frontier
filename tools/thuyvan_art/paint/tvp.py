def squint_check(rgb_u8, name, out_rel=None):
    """Style guide 3.2 step 11: squint (1/16 and back) and a 3 x 3 tile at 1/8. Writes <name>_check.png and returns
    the numbers: mean value, contrast range, the largest blob deviation at 1/16 (must stay <= 0.25)."""
    im = Image.fromarray(rgb_u8[..., :3])
    w, h = im.size
    sq = im.resize((max(w // 16, 1), max(h // 16, 1)), Image.BOX)
    sqv = np.asarray(sq, np.float32).mean(-1) / 255.0
    squint = sq.resize((w // 4, h // 4), Image.BICUBIC)
    small = im.resize((w // 8, h // 8), Image.BOX)
    tile = Image.new("RGB", (small.width * 3, small.height * 3))
    for j in range(3):
        for i in range(3):
            tile.paste(small, (i * small.width, j * small.height))
    tile = tile.resize((w // 4 * 3 // 2, h // 4 * 3 // 2), Image.BOX) if w >= 1024 else tile
    out = Image.new("RGB", (tile.width + squint.width + 24, max(tile.height, squint.height) + 16), (236, 230, 216))
    out.paste(tile, (8, 8))
    out.paste(squint, (tile.width + 16, 8))
    v = np.asarray(im, np.float32).mean(-1) / 255.0
    bs = max(w // 32, 1)  # a medium stroke's size: 1/32 of the tile
    sqv = v[:h // bs * bs, :w // bs * bs].reshape(h // bs, bs, w // bs, bs).mean((1, 3))
    stats = {"mean": round(float(v.mean()), 3), "p2": round(float(np.percentile(v, 2)), 3),
             "p98": round(float(np.percentile(v, 98)), 3),
             "blob_dev": round(float(np.abs(sqv - sqv.mean()).max()), 3)}
    path = look_path("checks/%s_check.png" % name) if out_rel is None else out_rel
    out.save(path)
    return stats
