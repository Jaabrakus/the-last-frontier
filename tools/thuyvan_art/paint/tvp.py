"""Thủy Vân painter core (look builder PAINT): a deterministic numpy brush engine for hand-painted tiling textures.

The style guide (look/style_guide.md, section 3.2) is the recipe this module implements:

    ramp -> base + low-frequency variation (periods 1 and 1/2 of the tile) -> big flat dabs (firm painter's edge,
    flow field) -> medium strokes painted three times (dark copy under, body, light sliver on top) -> stroke height
    map -> cavity AO toward a cool dark -> edge highlight (rock, wood) -> accents -> 0.6 px blur + unsharp mask ->
    clamp to the ramp's span -> value budget -> squint and 3 x 3 tiling check.

Everything is painted on a torus (every dab wraps), in linear float, with fixed seeds: a texture rebuilds bit for bit.
Colours come only from tools/thuyvan_art/paint/palettes.json (a verbatim copy of look/palettes.json, generated by
look/palettes.py); nobody retypes hex values. No photographs, no external images: everything is our own.
"""
