#!/usr/bin/env python3
"""Writes data/world/maps/r1/region.json: R1 as the game reads it (WorldRegion "r1"; its squares.json beside it is
T4's terrain baker's recipes, a different schema, so the game's squares file is region.json: WorldRegion.squares_path).

    python3 tools/thuyvan_art/terrain/write_r1_region.py [--check]

From the lead's layout.json and T3's water.json (never edited here):
  grid      the layout's 3 x 4 cells (rows north to south), as WorldSquares reads a grid: its middle row index
            (4 - 1) // 2 = 1, so row 1 is square y -1; with the region block's terrain_origin [0, -416] FrontierTerrain
            centres square (c - 1, r - 2) on the layout's cell centre (B2, square (0, 0), is the packed root)
  types     the layout's cell types with WorldSquares' fields (name; trees, stone, water as the recipes give them);
            no animals (R1 has no wildlife spawner yet)
  river     WaterNetwork.as_world_river_block("main") (WorldRiver's nodes: [z, x, level, half_width] every NODE_STEP m,
            the bank its widest half width + BANK_PAD, the Silent Reach as the still reach)
  region    the block ThuyVanLevel / ThuyVanR1Level reads: names (proposal), the season and start, the packed ground
            (terrain_dir, terrain_origin), the look ("cycle": the owner's day cycle, owner_answers.md 7), the player's
            start (the east bridge head, facing the rope bridge)
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
MAPS = os.path.join(ROOT, "data", "world", "maps", "r1")
OUT = os.path.join(MAPS, "region.json")
NODE_STEP = 16.0
BANK_PAD = 6.0

TYPES = {
    "high_pass": {"name": "high pass", "trees": 0.3, "stone": 1.0, "water": "spring"},
    "terraced_slope": {"name": "terraced slope", "trees": 0.4, "stone": 0.3, "water": "paddy", "built": True},
    "gorge": {"name": "gorge", "trees": 0.6, "stone": 1.0, "water": "river"},
    "bridge_gorge": {"name": "bridge gorge", "trees": 0.5, "stone": 1.0, "water": "torrent", "built": True},
    "switchbacks": {"name": "switchbacks", "trees": 0.9, "stone": 0.4, "water": "spring", "built": True},
    "middle_reach": {"name": "middle reach", "trees": 0.5, "stone": 0.3, "water": "river", "built": True},
    "stone_height": {"name": "stone height", "trees": 0.5, "stone": 0.8, "water": "spring", "built": True},
    "foothill_paddies": {"name": "foothill paddies", "trees": 0.3, "stone": 0.2, "water": "paddy", "built": True},
    "river_flats_lock": {"name": "river flats and lock", "trees": 0.4, "stone": 0.3, "water": "river", "built": True},
    "rim": {"name": "rim", "trees": 0.8, "stone": 0.6, "water": "spring"},
    "river_exit_karst": {"name": "river exit and first karst", "trees": 0.5, "stone": 0.6, "water": "river"},
}


def build():
    layout = json.load(open(os.path.join(MAPS, "layout.json"), encoding="utf-8"))
    water = json.load(open(os.path.join(MAPS, "water.json"), encoding="utf-8"))
    g = layout["grid"]
    grid = [[g["cells"]["%s%s" % (c, r)] for c in g["cols"]] for r in g["rows"]]
    main = next(c for c in water["channels"] if c["id"] == "main")
    fields = water["node_fields"]
    iz, ix, il, ih = fields.index("z"), fields.index("x"), fields.index("level"), fields.index("half_width")
    nodes, bank, last = [], 0.0, None
    rows = main["nodes"]
    for k, r in enumerate(rows):
        if last is not None and r[iz] - last < NODE_STEP and k != len(rows) - 1:
            continue
        nodes.append([round(r[iz], 2), round(r[ix], 3), round(r[il], 3), round(r[ih], 2)])
        bank = max(bank, r[ih])
        last = r[iz]
    reaches = [{"id": r["id"], "z_from": float(r["z_from"]), "z_to": float(r["z_to"]), "ease_m": float(r["ease_m"]),
                "scale_by_state": dict(r["scale_by_state"])} for r in main.get("reaches", [])]
    return {
        "_doc": [
            "R1 as the game reads it (WorldRegion 'r1': WorldRegion.squares_path prefers this file, since squares.json "
            "beside it is the terrain baker's). GENERATED by tools/thuyvan_art/terrain/write_r1_region.py from "
            "layout.json and water.json; edit the generator, not this file.",
            "grid: the layout's cells, rows north to south (WorldSquares: row 1 is square y -1). The ground is T4's bake "
            "packed by tools/thuyvan_look/pack_r1_terrain.gd into terrain_dir; terrain_origin moves FrontierTerrain's "
            "square grid so square (c - 1, r - 2) sits on the layout's cell centre.",
            "river: the main channel as WorldRiver's nodes [z, x, level, half_width] (WaterNetwork.as_world_river_block); "
            "the torrent and the pounds are WaterNetwork's only (ThuyVanWater draws them).",
        ],
        "size_m": float(layout["square_m"]),
        "region": {
            "id": "r1",
            "name": "Đá Trắng",
            "title": "the White Stone Reach",
            "title_status": "proposal",
            "latitude_deg": 21.0,
            "season": "early_rains",
            "start_day": "may_mid",
            "day_of_year": 135.0,
            "start_hour": 13.0,
            "terrain_dir": "res://assets/thuyvan/terrain/r1/",
            "terrain_origin": [0.0, -416.0],
            "look": "cycle",
            "water": "res://data/world/maps/r1/water.json",
            "player_at": [912.0, -1236.0],
            "player_face": [820.0, -1215.0],
        },
        "river": {
            "channel": "main",
            "node_fields": ["z", "x", "level", "half_width"],
            "nodes": nodes,
            "bank": round(bank + BANK_PAD, 2),
            "reaches": reaches,
            "rapids": [],
        },
        "grid": grid,
        "types": {k: TYPES[k] for k in sorted({t for row in grid for t in row})},
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if args.check:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("region.json: %s" % ("same" if same else "DIFFERS (rerun write_r1_region.py)"))
        sys.exit(0 if same else 1)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
