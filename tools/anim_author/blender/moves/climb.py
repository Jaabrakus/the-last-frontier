def shape(spec, frames):
    """Over the ledge the torso leans well forward; on the wall the knees stay outside it; the head is not driven into the lip."""
    c = 0.0
    for f in frames:
        P, t = f["P"], f["t"]
        if 1.3 <= t <= 1.9:
            pitch = math.degrees((P["spined"] - P["pelvis"]).angle(Vector((0, 1, 0))))
            c += max(0.0, 32.0 - pitch) ** 2 * 0.03
        if t < 1.6:
            for s in ("l", "r"):
                c += max(0.0, P[s + "_knee"].z - 0.22) ** 2 * 50.0
    return c


